def make_tmy3_meta(n_stations: int = 1020) -> pd.DataFrame:
    rows = []
    for i in range(n_stations):
        st = STATE_DF.iloc[i % len(STATE_DF)]
        rows.append({
            "station_number": 690000 + i * 137,
            "station_name": f"STATION {st['postal']} {i:04d}",
            "State": st["postal"],
            "Latitude": round(27 + (hash(st["postal"]) % 180) / 10.0 + RNG.normal(0, 1.2), 3),
            "Longitude": round(-125 + (hash(st["postal"][::-1]) % 550) / 10.0, 3),
            "Elevation": int(abs(RNG.normal(400, 500))),
            "Class": RNG.choice(["I", "II", "III"], p=[0.5, 0.3, 0.2]),
        })
    return pd.DataFrame(rows)


def make_tmy3_hourly(meta: pd.DataFrame, n_stations: int = 12) -> pd.DataFrame:
    chosen = meta.iloc[:: max(1, len(meta) // n_stations)].iloc[:n_stations]
    frames = []
    hours = np.arange(8760)
    doy = hours // 24 + 1
    hod = hours % 24
    date = pd.to_datetime("2020-01-01") + pd.to_timedelta(hours, unit="h")
    for _, stn in chosen.iterrows():
        lat = stn["Latitude"]
        st_row = STATE_DF[STATE_DF["postal"] == stn["State"]].iloc[0]
        tmean = 18 - 0.30 * (st_row["hdd"] - 4500) / 1000 * 2 + 0.002 * st_row["cdd"]
        seasonal = -12 * np.cos(2 * np.pi * (doy - 15) / 365) * np.clip((lat - 20) / 25, 0.3, 1.2)
        diurnal = 4.5 * np.sin(2 * np.pi * (hod - 8) / 24)
        tdb = tmean + seasonal + diurnal + RNG.normal(0, 3, 8760)
        ghi = np.clip(650 * np.sin(np.pi * np.clip(hod - 6, 0, 12) / 12) *
                      (0.55 + 0.45 * np.sin(2 * np.pi * (doy - 80) / 365)) *
                      _ln(1, .3, 8760), 0, None)
        dew = np.clip(tdb - RNG.uniform(4, 14, 8760), -30, None)
        rh = np.clip(100 * np.exp((17.27 * dew) / (237.3 + dew) - (17.27 * tdb) / (237.3 + tdb)), 1, 100)
        wspd = np.clip(RNG.gamma(2.2, 1.6, 8760), 0, 40)
        df = pd.DataFrame({
            "Station number": stn["station_number"],
            "Date (MM/DD/YYYY)": date.strftime("%m/%d/%Y"),
            "Time (HH:MM)": [f"{h:02d}:00" for h in hod],
            "GHI (W/m^2)": ghi.round(0), "Dry-bulb (C)": tdb.round(1),
            "Dew-point (C)": dew.round(1), "RHum (%)": rh.round(0),
            "Wspd (m/s)": wspd.round(1),
        })
        for c in TMY3_COLUMNS:
            if c not in df.columns:
                if "source" in c.lower():
                    df[c] = RNG.choice([1, 3, 5, 9], 8760)
                elif "uncert" in c.lower():
                    df[c] = RNG.uniform(0, 5, 8760).round(1)
                elif "Date" in c or "Time" in c or "METAR" in c:
                    df[c] = ""
                else:
                    df[c] = RNG.uniform(0, 100, 8760).round(1)
        frames.append(df[TMY3_COLUMNS])
    return pd.concat(frames, ignore_index=True)


