UPGRADE_DELTA = {0: 0.0, 3: 0.25, 4: 0.27, 10: 0.06, 11: 0.08, 15: 0.05}
_RS_STOCK_CACHE: dict = {}

RS_BA = ["Hot-Humid", "Hot-Dry", "Marine", "Mixed-Humid", "Mixed-Dry", "Cold", "Very-Cold"]
RS_TYPEHUQ = ["Single-Family Detached", "Single-Family Attached", "Mobile Home",
              "Multi-Family with 2 - 4 Units", "Multi-Family with 5+ Units"]
RS_VINTAGE = ["<1940", "1940s", "1950s", "1960s", "1970s", "1980s", "1990s",
              "2000s", "2010s"]
RS_FUEL = ["Electricity", "Natural Gas", "Propane", "Fuel Oil", "Other Fuel", "Wood"]


def _make_resstock_stock(n_rows: int) -> pd.DataFrame:
    """The SHARED building stock (generated once for the largest request)."""
    if "stock" in _RS_STOCK_CACHE and len(_RS_STOCK_CACHE["stock"]) >= n_rows:
        return _RS_STOCK_CACHE["stock"]
    n = n_rows
    ba = RNG.choice(RS_BA, n, p=[0.28, 0.08, 0.10, 0.24, 0.07, 0.18, 0.05])
    th = RNG.choice(RS_TYPEHUQ, n, p=[0.63, 0.07, 0.06, 0.10, 0.14])
    sqft = np.clip(_ln(1.0, 0.35, n) * np.where(th == "Single-Family Detached", 2300, 1400),
                   300, 6000)
    vintage = RNG.choice(RS_VINTAGE, n)
    fuel = RNG.choice(RS_FUEL, n, p=[0.38, 0.42, 0.06, 0.06, 0.04, 0.04])
    hdd = np.array([{"Hot-Humid": 1600, "Hot-Dry": 1800, "Marine": 4200,
                     "Mixed-Humid": 4300, "Mixed-Dry": 4500, "Cold": 6500,
                     "Very-Cold": 9000}[b] for b in ba])
    cdd = np.array([{"Hot-Humid": 3200, "Hot-Dry": 3000, "Marine": 450,
                     "Mixed-Humid": 1500, "Mixed-Dry": 1200, "Cold": 700,
                     "Very-Cold": 350}[b] for b in ba])
    ua = sqft * RNG.uniform(0.25, 0.55, n)
    heat = ua * hdd * 24 / 3412 * 0.28 * RNG.uniform(0.8, 1.3, n)
    cool = ua * cdd * 24 / 3412 * 0.28 * RNG.uniform(0.7, 1.2, n) * 0.30
    base_other = (8 + sqft / 400) * 365 * RNG.uniform(0.8, 1.3, n) / 1000 * 2.2
    stock = pd.DataFrame({"ba": ba, "th": th, "sqft": sqft, "vintage": vintage,
                          "fuel": fuel, "hdd": hdd, "cdd": cdd, "ua": ua,
                          "heat": heat, "cool": cool, "base_other": base_other})
    _RS_STOCK_CACHE["stock"] = stock
    return stock


def make_resstock_upgrade(upgrade_id: int, n_rows: int) -> pd.DataFrame:
    """All upgrade files share the SAME leading buildings (like real ResStock);
    only the out.* energy results change with the measure."""
    stock = _make_resstock_stock(n_rows).iloc[:n_rows]
    n = len(stock)
    sqft = stock["sqft"].values
    fuel = stock["fuel"].values.copy()
    heat = stock["heat"].values.copy()
    cool = stock["cool"].values.copy()
    base_other = stock["base_other"].values.copy()

    delta = UPGRADE_DELTA.get(upgrade_id, 0.0)
    if upgrade_id in (3, 4):
        heat = heat * (1 - delta) * RNG.uniform(0.9, 1.1, n)
        cool = cool * 0.98
        fuel = np.where(RNG.random(n) < 0.9, "Electricity", fuel)
    elif upgrade_id == 10:
        heat = heat * (1 - 0.06 * RNG.uniform(0.6, 1.4, n))
        cool = cool * (1 - 0.04 * RNG.uniform(0.6, 1.4, n))
    elif upgrade_id == 11:
        heat = heat * (1 - 0.08 * RNG.uniform(0.6, 1.4, n))
        cool = cool * (1 - 0.05 * RNG.uniform(0.6, 1.4, n))
    elif upgrade_id == 15:
        heat = heat * (1 - 0.05 * RNG.uniform(0.6, 1.4, n))
        cool = cool * (1 - 0.07 * RNG.uniform(0.6, 1.4, n))

    total_kwh = np.clip(heat + cool + base_other, 500, 45000)
    elec_share = np.where(fuel == "Electricity", 0.95, RNG.uniform(0.35, 0.6, n))
    elec_kwh = total_kwh * elec_share
    gas_kwh = total_kwh - elec_kwh
    th = stock["th"].values
    ba = stock["ba"].values

    # Make the intervention visible in the in.* attributes (real ResStock
    # upgrade files carry modified building characteristics — without this the
    # upgrade teachers see identical inputs and cannot learn the effect).
    infiltration = RNG.choice(["15 ACH50", "10 ACH50", "7 ACH50"], n)
    insul_roof = RNG.choice(["R-30", "R-38", "R-49"], n)
    insul_ceiling = RNG.choice(["R-19", "R-30", "R-49"], n)
    windows = RNG.choice(["Single, Clear", "Double, Clear", "Double, Low-E"], n)
    if upgrade_id == 10:      # air sealing
        infiltration = np.where(RNG.random(n) < 0.9, "7 ACH50", infiltration)
    elif upgrade_id == 11:    # attic insulation
        insul_roof = np.where(RNG.random(n) < 0.9, "R-49", insul_roof)
        insul_ceiling = np.where(RNG.random(n) < 0.9, "R-49", insul_ceiling)
    elif upgrade_id == 15:    # ENERGY STAR windows
        windows = np.where(RNG.random(n) < 0.9, "Double, Low-E", windows)

    df = pd.DataFrame({
        "bldg_id": np.arange(1, n + 1),           # stable id for upgrade matching
        "in.sqft..ft2": sqft.round(0),
        "in.geometry_building_type_recs": th,
        "in.vintage": stock["vintage"].values,
        "in.geometry_stories": RNG.choice(["One", "Two", "Three"], n, p=[0.55, 0.38, 0.07]),
        "in.bedrooms": RNG.choice(["1", "2", "3", "4", "5"], n, p=[0.1, 0.25, 0.4, 0.2, 0.05]),
        "in.occupants": RNG.choice(["1", "2", "3", "4", "5", "6"], n,
                                   p=[0.25, 0.35, 0.18, 0.12, 0.07, 0.03]),
        "in.heating_fuel": fuel,
        "in.hvac_heating_type": np.where(fuel == "Electricity", "Heat Pump", "Central Furnace"),
        "in.hvac_heating_efficiency": np.where(fuel == "Electricity", "9.5 HSPF", "80% AFUE"),
        "in.hvac_cooling_type": RNG.choice(["Central AC", "Room AC", "None"], n,
                                           p=[0.65, 0.2, 0.15]),
        "in.hvac_cooling_efficiency": "13 SEER",
        "in.insulation_wall": RNG.choice(["R-13", "R-19", "R-21"], n),
        "in.insulation_roof": insul_roof,
        "in.insulation_ceiling": insul_ceiling,
        "in.infiltration": infiltration,
        "in.windows": windows,
        "in.building_america_climate_zone": ba,
        "in.ashrae_iecc_climate_zone_2004": [b.split("-")[0] for b in ba],
        "in.census_region": RNG.choice(["South", "West", "Midwest", "Northeast"], n),
        "in.census_division": RNG.choice(["Pacific", "South Atlantic", "West North Central"], n),
        "in.state": RNG.choice(STATE_DF["postal"].tolist(), n),
        "in.county": RNG.choice(["G0100010", "G0600030", "G4802010"], n),
        "in.puma": RNG.choice(["G01000100", "G06000200"], n),
        "in.weather_file_city": RNG.choice(["USA_AZ_Phoenix", "USA_MN_Minneapolis"], n),
        "in.water_heater_fuel": RNG.choice(["Electricity", "Natural Gas"], n),
        "in.water_heater_efficiency": "0.9 EF",
        "in.has_pv": RNG.choice(["No", "Yes"], n, p=[0.92, 0.08]),
        "in.electric_vehicle_ownership": RNG.choice(["No", "Yes"], n, p=[0.85, 0.15]),
        "in.lighting": "LED",
        "in.ceiling_fan": RNG.choice(["No", "Yes"], n),
        "in.mechanical_ventilation": RNG.choice(["No", "Yes"], n, p=[0.7, 0.3]),
        "out.site_energy.total.energy_consumption..kwh": total_kwh.round(1),
        "out.electricity.total.energy_consumption..kwh": elec_kwh.round(1),
        "out.natural_gas.total.energy_consumption..kwh": np.clip(gas_kwh, 0, None).round(1),
        "out.site_energy.total.energy_consumption_intensity..kwh_per_ft2":
            (total_kwh / np.clip(sqft, 1, None)).round(3),
        "out.utility_bills.total_bill..usd": (total_kwh * 0.13).round(0),
        "out.emissions.total.lrmer_mid_case_25..co2e_kg": (total_kwh * 0.42).round(0),
        "upgrade": upgrade_id,
        "in.upgrade_name": f"upgrade_{upgrade_id}",
        "weight": RNG.uniform(200, 300, n).round(1),
    })
    return df


