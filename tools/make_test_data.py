def _ln(mean=1.0, sigma=0.4, n=1):
    return RNG.lognormal(np.log(mean) - sigma ** 2 / 2, sigma, n)


# ===========================================================================
# RECS 2020
# ===========================================================================
def make_recs(n_rows: int) -> pd.DataFrame:
    n = n_rows
    st_idx = RNG.choice(len(STATE_DF), n, p=STATE_DF["w"] / STATE_DF["w"].sum())
    st = STATE_DF.iloc[st_idx].reset_index(drop=True)

    hdd = np.clip(st["hdd"].values * _ln(1, 0.12, n), 0, None)
    cdd = np.clip(st["cdd"].values * _ln(1, 0.12, n), 0, None)

    def ba_zone(h, c):
        if h >= 7000: return "Very-Cold"
        if h >= 5000: return "Cold"
        if h >= 3800 and c < 2000: return "Marine" if RNG.random() < 0.3 else "Mixed-Humid"
        if c >= 2500: return "Hot-Humid" if RNG.random() < 0.7 else "Hot-Dry"
        return "Mixed-Humid" if RNG.random() < 0.6 else "Mixed-Dry"

    ba = [ba_zone(h, c) for h, c in zip(hdd, cdd)]

    typehuq = RNG.choice([1, 2, 3, 4, 5], n, p=[0.06, 0.63, 0.06, 0.10, 0.15])
    sqft = np.clip(_ln(1, 0.35, n) * np.where(typehuq == 2, 2300,
                    np.where(typehuq == 1, 1100, 1400)), 200, 15000).round(0)
    stories = np.where(typehuq == 1, 1,
                       np.where(typehuq >= 4, RNG.choice([1, 2, 3], n, p=[0.4, 0.4, 0.2]),
                                RNG.choice([1, 2, 3], n, p=[0.45, 0.45, 0.1]))).astype(float)
    bedrooms = np.clip((sqft / 600 + RNG.normal(0, 0.6, n)).round(0), 0, 6)
    occ = np.clip(RNG.poisson(2.2, n) + 1, 1, 10).astype(float)
    yearrange = RNG.choice(np.arange(1, 12), n,
                           p=[0.09, 0.07, 0.09, 0.11, 0.13, 0.13, 0.12, 0.11, 0.07, 0.05, 0.03])
    walltype = RNG.choice([1, 2, 3, 4, 5, 6, 7], n,
                          p=[0.08, 0.50, 0.10, 0.12, 0.08, 0.05, 0.07])
    rooftype = RNG.choice([1, 2, 3, 4, 5, 6], n, p=[0.55, 0.15, 0.10, 0.05, 0.10, 0.05])
    adqinsul = np.where(yearrange <= 3,
                        RNG.choice([1, 2, 3, 4], n, p=[0.30, 0.35, 0.25, 0.10]),
                        RNG.choice([1, 2, 3, 4], n, p=[0.15, 0.30, 0.35, 0.20]))
    typeglass = np.where(yearrange <= 4, RNG.choice([1, 2, 3], n, p=[0.5, 0.45, 0.05]),
                         RNG.choice([1, 2, 3], n, p=[0.15, 0.75, 0.10]))
    windows = np.clip((sqft / 400 + RNG.normal(0, 1.5, n)).round(0), 1, 12).astype(float)
    drafty = np.where(yearrange <= 4,
                      RNG.choice([1, 2, 3, 4], n, p=[0.25, 0.35, 0.25, 0.15]),
                      RNG.choice([1, 2, 3, 4], n, p=[0.10, 0.25, 0.40, 0.25]))
    highceil = (RNG.random(n) < 0.25).astype(float)

    south = np.isin(st["region"].values, ["S"])
    cold = hdd > 5500
    fuelheat = np.where(
        south & (RNG.random(n) < 0.55), 5,
        np.where(cold & (RNG.random(n) < 0.65), 1,
                 RNG.choice([1, 2, 3, 5, 7], n, p=[0.45, 0.07, 0.08, 0.35, 0.05]))).astype(float)
    equipm = np.where(fuelheat == 5,
                      np.where(cold & (RNG.random(n) < 0.35), 10, RNG.choice([3, 10, 12], n, p=[0.3, 0.3, 0.4])),
                      RNG.choice([3, 4, 5, 7], n, p=[0.65, 0.05, 0.2, 0.1])).astype(float)
    aircond = (RNG.random(n) < np.where(south, 0.92, 0.72)).astype(float)
    typeac = np.where(aircond == 1, RNG.choice([1, 2], n, p=[0.7, 0.3]), 0).astype(float)

    # ---------------- physics-consistent energy model (kBtu) ----------------
    ceil_h = 9.0
    height = stories * ceil_h
    footprint = sqft / stories
    perimeter = 4 * np.sqrt(np.clip(footprint, 25, None))
    wall_area = perimeter * height
    u_wall = pd.Series(walltype).map({1: .30, 2: .18, 3: .25, 4: .20, 5: .22, 6: .35, 7: .28}).fillna(.22).values
    insul_f = pd.Series(adqinsul).map({1: 1.25, 2: 1.0, 3: 0.8, 4: 0.65}).fillna(1.0).values
    u_glass = pd.Series(typeglass).map({1: 1.0, 2: 0.55, 3: 0.35}).fillna(.65).values
    win_area = wall_area * np.clip(0.06 + 0.02 * windows, 0.08, 0.30)
    ach50 = pd.Series(drafty).map({1: 14., 2: 10., 3: 6.5, 4: 4.}).fillna(9.).values
    ua = (u_wall * insul_f * np.clip(wall_area - win_area, 0, None)
          + u_glass * win_area + 0.08 * insul_f * footprint + 0.10 * footprint
          + 0.018 * sqft * ceil_h * ach50 / 20)
    is_hp = (fuelheat == 5) & (equipm == 10)
    equip_factor = pd.Series(equipm).map({3: 1.00, 4: 0.85, 5: 0.92, 7: 0.88,
                                          10: 1.00, 12: 1.00}).fillna(0.95).values
    heat_eff = np.where(is_hp, 2.3, np.where(fuelheat == 5, 0.98,
                        pd.Series(fuelheat).map({1: .80, 2: .78, 3: .78, 7: .55}).fillna(.80).values
                        * equip_factor))
    beh = _ln(1.0, 0.25, n)  # behavioral/occupant variance — the irreducible part

    heat_load = ua * hdd * 24 / 1000 * beh
    totalbtusph = np.clip(heat_load / heat_eff * 0.30, 0, None)           # calib
    cool_load = (ua * 0.8 + 0.5 * 0.018 * sqft * ceil_h * ach50 / 20) * cdd * 24 / 1000
    cool_eff = np.where(typeac == 1, 3.2, np.where(typeac == 2, 2.6, 3.0))
    btuelcol = np.clip(cool_load / (cool_eff / 3.412) * aircond * beh * 0.20, 0, None)
    totalbtuwth = np.clip(occ * 25 * 8.34 * 70 * 365 / 1000 * beh *
                          np.where(fuelheat == 5, 1 / .92, 1 / .62) * 0.62, 0, None)
    btuellgt = np.clip((sqft / 90 * 125 + 500) * (1 - 0.5 * RNG.uniform(0, 1, n)) * beh * 1.05, 0, None)
    btuelrfg = np.clip(3200 * _ln(1, 0.25, n), 0, None)
    btuelapl = np.clip((occ * 1400 + sqft * 4.5 + 4000) * _ln(1, 0.30, n), 0, None)
    btuelplt = 0.30 * btuelapl
    btuelcok = np.where(RNG.random(n) < 0.6, 800 * _ln(1, 0.2, n), 0)

    elec_heat = np.where(fuelheat == 5, totalbtusph, 0)
    gas_heat = np.where(fuelheat == 1, totalbtusph, 0)
    fo_heat = np.where(fuelheat == 2, totalbtusph, 0)
    lp_heat = np.where(fuelheat == 3, totalbtusph, 0)
    elec_dhw = np.where(fuelheat == 5, totalbtuwth, 0)
    gas_dhw = np.where(fuelheat == 1, totalbtuwth, 0)

    btuel = elec_heat + btuelcol + elec_dhw + btuellgt + btuelrfg + btuelapl + btuelplt + btuelcok
    btung = gas_heat + gas_dhw
    btufo = fo_heat
    btulp = lp_heat
    totalbtu = btuel + btung + btufo + btulp
    kwh = btuel / 3.412

    df = pd.DataFrame({
        "DOEID": np.arange(1, n + 1),
        "REGIONC": st["region"].map({"W": "W", "S": "S", "MW": "MW", "NE": "NE"}).values,
        "DIVISION": st["division"].values,
        "STATE_FIPS": [f"{i % 56 + 1:02d}" for i in st_idx],
        "state_postal": st["postal"].values,
        "state_name": st["name"].values,
        "BA_climate": ba,
        "IECC_climate_code": [b.split("-")[0] for b in ba],
        "HDD65": hdd.round(0), "CDD65": cdd.round(0),
        "HDD30YR_PUB": (hdd * _ln(1, .05, n)).round(0),
        "CDD30YR_PUB": (cdd * _ln(1, .05, n)).round(0),
        "TYPEHUQ": typehuq, "TOTSQFT_EN": sqft, "STORIES": stories,
        "BEDROOMS": bedrooms.astype(float),
        "TOTROOMS": np.clip(bedrooms + RNG.poisson(3, n), 1, 15).astype(float),
        "NCOMBATH": np.clip(bedrooms / 2, 1, 4).round(0),
        "NHAFBATH": (RNG.random(n) < .4).astype(float),
        "NHSLDMEM": occ, "YEARMADERANGE": yearrange.astype(float),
        "KOWNRENT": RNG.choice([1, 2], n, p=[.66, .34]).astype(float),
        "WALLTYPE": walltype.astype(float), "ROOFTYPE": rooftype.astype(float),
        "ADQINSUL": adqinsul.astype(float), "TYPEGLASS": typeglass.astype(float),
        "WINDOWS": windows, "DRAFTY": drafty.astype(float),
        "HIGHCEIL": highceil, "FUELHEAT": fuelheat, "EQUIPM": equipm,
        "AIRCOND": aircond, "TYPEAC": typeac,
        "NUMFRIG": np.clip(RNG.poisson(1.1, n), 0, 4).astype(float),
        "TVCOLOR": np.clip(RNG.poisson(1.8, n), 0, 8).astype(float),
        "NUMPC": np.clip(RNG.poisson(1.2, n), 0, 6).astype(float),
        "DWASHER": (RNG.random(n) < .65).astype(float),
        "CWASHER": (RNG.random(n) < .8).astype(float),
        "DRYER": (RNG.random(n) < .75).astype(float),
        "SWIMPOOL": (RNG.random(n) < .06).astype(float),
        "RECFRIG": (RNG.random(n) < .25).astype(float),
        "HUMIDIF": (RNG.random(n) < .2).astype(float),
        "SMARTMETER": (RNG.random(n) < .45).astype(float),
        "INTELLIGHT": (RNG.random(n) < .15).astype(float),
        "SOLAR": (RNG.random(n) < .06).astype(float),
        "EV": (RNG.random(n) < .08).astype(float),
        "NWEIGHT": RNG.uniform(437, 29279, n).round(0),
        "TOTALBTU": totalbtu.round(0), "TOTALBTUSPH": totalbtusph.round(0),
        "TOTALBTUWTH": totalbtuwth.round(0),
        "BTUELCOL": btuelcol.round(0), "BTUELLGT": btuellgt.round(0),
        "BTUELSPH": elec_heat.round(0), "BTUELWTH": elec_dhw.round(0),
        "BTUELRFG": btuelrfg.round(0), "BTUELAPL": btuelapl.round(0),
        "BTUEL": btuel.round(0), "KWH": kwh.round(0),
        "BTUNG": btung.round(0), "THERMS": (btung / 100).round(0),
        "BTUFO": btufo.round(0), "BTULP": btulp.round(0),
        "TOTALDOL": (btuel * 0.037 + btung * 0.011).round(0),
    })

    # ---- structural filler ------------------------------------------------
    # imputation flags + replicate weights + a few generic survey columns
    for i in range(1, 61):
        df[f"NWEIGHT{i}"] = (df["NWEIGHT"] * _ln(1, .15, n)).round(0)
    for z in ["ZTOTSQFT", "ZNHSLDMEM", "ZFUELHEAT", "ZEQUIPM", "ZAIRCOND",
              "ZTYPEGLASS", "ZADQINSUL", "ZWALLTYPE", "ZDRAFTY", "ZWINDOWS"]:
        df[z] = (RNG.random(n) < 0.08).astype(float)
    for i in range(30):
        df[f"APPLFLAG{i:02d}"] = (RNG.random(n) < RNG.uniform(0.05, 0.6)).astype(float)

    # ---- exact codebook structure when available --------------------------
    if CODEBOOK.exists():
        try:
            cb = pd.read_excel(CODEBOOK, sheet_name=0)
            name_col = [c for c in cb.columns if "variable" in str(c).lower()
                        or "name" in str(c).lower()][0]
            all_vars = [str(v).strip() for v in cb[name_col].dropna()]
            if len(all_vars) > 200:
                for v in all_vars:
                    if v not in df.columns:
                        if v.startswith("Z") and len(v) > 1:
                            df[v] = (RNG.random(n) < 0.05).astype(float)
                        elif v[:1].isalpha() and not any(ch.isdigit() for ch in v):
                            df[v] = np.where(RNG.random(n) < 0.1, -2, 0).astype(float)
                        else:
                            df[v] = np.where(RNG.random(n) < 0.15, -2,
                                             RNG.uniform(0, 5, n)).round(0)
                df = df[[v for v in all_vars if v in df.columns] +
                        [c for c in df.columns if c not in all_vars]]
                print(f"  [codebook] structure aligned: {len(all_vars)} variables")
        except Exception as e:
            print(f"  [codebook] skipped ({e})")
    return df


