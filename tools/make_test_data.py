def make_spatial_lookup(n_rows: int = 200) -> pd.DataFrame:
    cols = [f"col_{i}" for i in range(27)]
    df = pd.DataFrame(RNG.uniform(0, 1, (n_rows, 27)), columns=cols)
    df["col_0"] = [f"G{(i % 56) + 1:02d}{(i % 900) + 10:04d}0" for i in range(n_rows)]
    return df


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--recs-rows", type=int, default=4000)
    ap.add_argument("--resstock-rows", type=int, default=8000)
    ap.add_argument("--tmy3-stations", type=int, default=12)
    ap.add_argument("--meta-stations", type=int, default=1020)
    args = ap.parse_args()

    DATA.mkdir(parents=True, exist_ok=True)
    print(f"[1/5] Generating RECS ({args.recs_rows:,} rows)...")
    recs = make_recs(args.recs_rows)
    recs.to_csv(DATA / "recs2020_public_v7.csv", index=False)
    print(f"      -> {DATA / 'recs2020_public_v7.csv'}  shape={recs.shape}")

    print(f"[2/5] Generating TMY3 meta ({args.meta_stations:,} stations)...")
    meta_path = DATA / "TMY3_StationsMeta.csv"
    if meta_path.exists():
        meta = pd.read_csv(meta_path)
        print(f"      -> real meta found, kept as-is ({len(meta):,} stations)")
    else:
        meta = make_tmy3_meta(args.meta_stations)
        meta.to_csv(meta_path, index=False)
        print(f"      -> {meta_path}  shape={meta.shape}")

    print(f"[3/5] Generating hourly TMY3 ({args.tmy3_stations} stations x 8760 h)...")
    tmy3 = make_tmy3_hourly(meta, args.tmy3_stations)
    tmy3.to_csv(DATA / "tmy3.csv", index=False)
    print(f"      -> {DATA / 'tmy3.csv'}  shape={tmy3.shape}")

    print("[4/5] Generating ResStock upgrades (shared building stock)...")
    _make_resstock_stock(max(args.resstock_rows, 8000))
    for u, frac in [(0, 1.0), (3, 1.0), (4, 1.0), (10, 0.56), (11, 0.92), (15, 0.98)]:
        dfu = make_resstock_upgrade(u, int(args.resstock_rows * frac))
        dfu.to_csv(DATA / f"upgrade{u}.csv.gz", index=False, compression="gzip")
        print(f"      -> {DATA / f'upgrade{u}.csv.gz'}  shape={dfu.shape}")

    print("[5/5] Generating spatial tract lookup...")
    sp = make_spatial_lookup()
    sp.to_csv(DATA / "spatial_tract_lookup_table.csv", index=False)
    print(f"      -> {DATA / 'spatial_tract_lookup_table.csv'}  shape={sp.shape}")
    print("DONE. All synthetic test data generated.")


if __name__ == "__main__":
    main()
